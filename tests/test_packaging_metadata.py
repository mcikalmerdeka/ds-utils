import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version


def _project_metadata():
    return tomllib.loads(Path("pyproject.toml").read_text(encoding="utf-8"))["project"]


def test_core_dependency_floors():
    dependencies = set(_project_metadata()["dependencies"])
    expected = {
        "scikit-learn>=1.6",
        "pandas>=2.2",
        "seaborn>=0.13",
        "statsmodels>=0.14",
        "numpy>=1.26",
        "scipy>=1.11",
    }

    assert expected <= dependencies


def test_optional_extra_floors():
    extras = _project_metadata()["optional-dependencies"]
    expected_text = {
        "beautifulsoup4>=4.12",
        "contractions>=0.1",
        "nltk>=3.9",
        "Pillow>=10",
        "textblob>=0.18",
        "wordcloud>=1.9",
    }
    expected_translate = {
        "deep-translator>=1.11",
        "langid>=1.1.6",
        "tenacity>=8.2",
    }

    assert expected_text <= set(extras["text"])
    assert expected_translate <= set(extras["translate"])


def test_project_identity_is_unchanged():
    project = _project_metadata()

    assert project["name"] == "data-science-utils"
    assert project["requires-python"] == ">=3.14"


def test_project_description_is_not_a_placeholder():
    description = _project_metadata()["description"]

    assert (
        description
        == "Reusable utilities for rapid EDA, preprocessing, modeling, and reporting"
    )


def _pinned_requirements():
    pinned = {}
    for line in Path("requirements.txt").read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or stripped.startswith("-"):
            continue

        requirement = Requirement(stripped)
        exact_pins = [
            specifier.version
            for specifier in requirement.specifier
            if specifier.operator == "=="
        ]
        if exact_pins:
            pinned[canonicalize_name(requirement.name)] = Version(exact_pins[0])

    return pinned


def test_requirements_txt_is_generated_from_pyproject():
    lines = Path("requirements.txt").read_text(encoding="utf-8").splitlines()

    assert "autogenerated by uv" in lines[0].lower()
    assert "uv export" in lines[1]

    pinned = _pinned_requirements()
    for dependency in _project_metadata()["dependencies"]:
        requirement = Requirement(dependency)
        name = canonicalize_name(requirement.name)
        assert name in pinned, f"{requirement.name} is missing from requirements.txt"
        assert requirement.specifier.contains(pinned[name]), (
            f"{requirement.name}=={pinned[name]} does not satisfy "
            f"{requirement.specifier}"
        )
